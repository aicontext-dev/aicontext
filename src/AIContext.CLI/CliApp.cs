using System.Globalization;

namespace AIContext.Cli;

// Argument parsing, console output and exit codes only; behavior lives in the AIContext library.
// Output streams and the working directory are injected so the whole CLI can be tested in-process.
public sealed class CliApp
{
    private const string CanonicalSchemaUrl = ContextSchema.CanonicalUrl;
    private const string ExpectedSpecVersion = "0.1.0";

    private static readonly string[] SupportedTargets = ExportTargets.Names.ToArray();

    private sealed record OptionSpec(string Name, bool TakesValue);

    private sealed record CommandSpec(string Name, string Usage, OptionSpec[] Options, string[] Help);

    private static readonly CommandSpec[] Commands =
    [
        new("init",
            "aicontext init [--path <directory>] [--name <project-name>] [--profile <core|extended>] [--force]",
            [new("path", true), new("name", true), new("profile", true), new("force", false)],
            [
                "Init options:",
                "  --profile   core (default): README.md and context.json. extended: also architecture.md, decisions.md and constraints.md."
            ]),
        new("validate",
            "aicontext validate [--path <directory>] [--strict]",
            [new("path", true), new("strict", false)],
            [
                "Validate options:",
                "  --strict    Treat warnings (missing recommended files, possible secrets) as errors."
            ]),
        new("export",
            $"aicontext export [--target <{string.Join("|", SupportedTargets)}|all>] [--path <directory>] [--layout <single|split>] [--force] [--dry-run] [--check]",
            [new("target", true), new("path", true), new("layout", true), new("force", false), new("dry-run", false), new("check", false)],
            [
                "Export options:",
                "  --target    Target to generate. Optional when exports.defaultTarget is set in context.json; --target always takes precedence.",
                "  --layout    single (default): one file per tool. split: small always-on file plus separate scoped/on-demand rule files.",
                "  --force     Overwrite existing files that were not generated by aicontext.",
                "  --dry-run   Show what would be written without changing any file.",
                "  --check     Like --dry-run, but exit with code 1 if any file is missing or out of date (for CI)."
            ]),
        new("status",
            "aicontext status [--path <directory>] [--layout <single|split>]",
            [new("path", true), new("layout", true)],
            [
                "Status:",
                "  Shows how much context each tool loads (always on vs. scoped/on-demand) and whether exports are in sync."
            ])
    ];

    private readonly TextWriter _out;
    private readonly TextWriter _err;
    private readonly string _workingDirectory;

    private CliApp(TextWriter output, TextWriter error, string workingDirectory)
    {
        _out = output;
        _err = error;
        _workingDirectory = workingDirectory;
    }

    public static int Run(string[] args, TextWriter output, TextWriter error, string? workingDirectory = null) =>
        new CliApp(output, error, workingDirectory ?? Environment.CurrentDirectory).Execute(args);

    private int Execute(string[] args)
    {
        if (args.Length == 0 || IsHelp(args[0]))
        {
            PrintHelp();
            return 0;
        }

        if (IsVersion(args[0]))
        {
            PrintVersion();
            return 0;
        }

        var command = Commands.FirstOrDefault(c => string.Equals(c.Name, args[0], StringComparison.Ordinal));
        if (command is null)
        {
            _err.WriteLine($"Unknown command '{args[0]}'.");
            PrintHelp();
            return 1;
        }

        var rest = args.Skip(1).ToArray();
        if (rest.Any(a => a is "-h" or "--help"))
        {
            PrintCommandHelp(command);
            return 0;
        }

        // Invalid arguments are rejected before anything runs, so a typo can never change what a command does.
        var (values, error) = ParseOptions(command, rest);
        if (error is not null)
        {
            _err.WriteLine(error);
            _err.WriteLine($"Run 'aicontext {command.Name} --help' for usage.");
            return 1;
        }

        return command.Name switch
        {
            "init" => RunInit(values),
            "validate" => RunValidate(values),
            "export" => RunExport(values),
            _ => RunStatus(values)
        };
    }

    private int RunInit(Dictionary<string, string?> options)
    {
        var basePath = GetBasePath(options);
        var force = IsTrue(options, "force");
        var projectName = GetOption(options, "name");
        if (string.IsNullOrWhiteSpace(projectName))
        {
            projectName = new DirectoryInfo(basePath).Name;
        }

        if (!ProjectInitializer.TryParseProfile(GetOption(options, "profile"), out var profile))
        {
            _err.WriteLine($"Unknown profile '{GetOption(options, "profile")}'. Use core or extended.");
            return 1;
        }

        var result = ProjectInitializer.Initialize(basePath, projectName, profile, CanonicalSchemaUrl, ExpectedSpecVersion, force);
        if (result.Conflicts.Count > 0)
        {
            foreach (var conflict in result.Conflicts)
            {
                _err.WriteLine($"File already exists: {conflict}. Use --force to overwrite.");
            }

            return 1;
        }

        foreach (var created in result.Created)
        {
            _out.WriteLine($"Created: {created}");
        }

        _out.WriteLine("Next: replace the TODO placeholders in .aicontext/ with real content; 'aicontext validate' reports them until you do.");

        var existing = ProjectInitializer.FindExistingInstructionFiles(basePath);
        if (existing.Count > 0)
        {
            _out.WriteLine();
            _out.WriteLine("These instruction files already exist and were not generated by aicontext:");
            foreach (var file in existing)
            {
                _out.WriteLine($"  {file}");
            }

            _out.WriteLine("Move their content into .aicontext/ (README.md, constraints.md, rules/) before you export; 'aicontext export' never overwrites them unless you pass --force.");
            _out.WriteLine("See recipe B in the user manual: \"I already have a hand-written AGENTS.md / CLAUDE.md / copilot-instructions\".");
        }

        return 0;
    }

    private int RunValidate(Dictionary<string, string?> options)
    {
        var basePath = GetBasePath(options);
        var strict = IsTrue(options, "strict");
        var validationResult = ContextValidator.ValidateDirectory(basePath, CanonicalSchemaUrl);

        foreach (var warning in validationResult.Warnings)
        {
            _out.WriteLine($"WARNING: {warning}");
        }

        var failureCount = validationResult.Errors.Count + (strict ? validationResult.Warnings.Count : 0);
        if (validationResult.Errors.Count > 0)
        {
            foreach (var error in validationResult.Errors)
            {
                _err.WriteLine($"ERROR: {error}");
            }
        }

        if (failureCount > 0)
        {
            var detail = strict && validationResult.Warnings.Count > 0
                ? $"{validationResult.Errors.Count} error(s) and {validationResult.Warnings.Count} warning(s) treated as errors (--strict)"
                : $"{validationResult.Errors.Count} error(s)";
            _err.WriteLine($"Validation failed with {detail}.");
            return 1;
        }

        var profile = validationResult.ExtendedProfile ? "Extended" : "Core";
        _out.WriteLine($"AIContext validation passed ({profile} profile).");
        _out.WriteLine("Validation checks structure and obvious placeholders, not whether the content is useful or up to date.");
        return 0;
    }

    private int RunExport(Dictionary<string, string?> options)
    {
        var basePath = GetBasePath(options);
        var check = IsTrue(options, "check");
        var preview = check || IsTrue(options, "dry-run");

        var plan = ExportService.Plan(new ExportRequest(
            basePath,
            GetOption(options, "target"),
            GetOption(options, "layout"),
            IsTrue(options, "force")));

        if (plan.DefaultTargetUsed is not null)
        {
            _out.WriteLine($"Using exports.defaultTarget '{plan.DefaultTargetUsed}' from .aicontext/context.json.");
        }

        foreach (var file in plan.Files)
        {
            _out.WriteLine($"{DescribeStatus(file.Status, preview || plan.HasErrors)} ({file.Target}): {file.Path}");
        }

        if (plan.HasErrors)
        {
            WriteErrors(plan.Diagnostics);
            _err.WriteLine(plan.Diagnostics.Any(IsContextError)
                ? "Fix the errors above (run 'aicontext validate' for details). No files were written."
                : "No files were written.");
            if (plan.Diagnostics.Any(d => d.Code == DiagnosticCodes.OverwriteConflict))
            {
                _err.WriteLine("Move the content of those files into .aicontext/ first, then use --force to replace them (recipe B in the user manual).");
            }

            return 1;
        }

        var changed = plan.ChangedCount;

        if (check)
        {
            if (changed > 0)
            {
                _err.WriteLine($"Export is out of date ({changed} file(s)). Run 'aicontext export' to update.");
                return 1;
            }

            _out.WriteLine("Export is up to date.");
            return 0;
        }

        if (preview)
        {
            _out.WriteLine($"Dry run: {changed} file(s) would change, nothing was written.");
            return 0;
        }

        var result = ExportService.Apply(plan);
        if (result.HasErrors)
        {
            WriteErrors(result.Diagnostics);
            _err.WriteLine(result.Changed == 0
                ? "No files were written."
                : $"{result.Changed} file(s) were already written. Run 'aicontext export' again.");
            return 1;
        }

        _out.WriteLine($"Export completed ({result.Changed} changed, {result.Unchanged} unchanged).");
        return 0;
    }

    // Context problems (1xxx and 2xxx) are the ones 'aicontext validate' reports as well.
    private static bool IsContextError(Diagnostic diagnostic) =>
        diagnostic.IsError &&
        (diagnostic.Code.StartsWith("AIC1", StringComparison.Ordinal) || diagnostic.Code.StartsWith("AIC2", StringComparison.Ordinal));

    private void WriteErrors(IEnumerable<Diagnostic> diagnostics)
    {
        foreach (var diagnostic in diagnostics.Where(d => d.IsError))
        {
            _err.WriteLine($"ERROR: {Describe(diagnostic)}");
        }
    }

    // The library words a missing target neutrally; the CLI names its own option.
    private static string Describe(Diagnostic diagnostic) =>
        diagnostic.Code == DiagnosticCodes.MissingTarget
            ? $"Missing required option: --target (or set exports.defaultTarget in .aicontext/context.json). Supported targets: {string.Join(", ", SupportedTargets)}, all"
            : diagnostic.Message;

    private static string DescribeStatus(ExportFileStatus status, bool preview) => status switch
    {
        ExportFileStatus.Created => preview ? "Would create" : "Created",
        ExportFileStatus.Updated => preview ? "Would update" : "Updated",
        ExportFileStatus.Deleted => preview ? "Would remove" : "Removed",
        ExportFileStatus.Unchanged => "Unchanged",
        ExportFileStatus.Blocked => "Blocked",
        _ => "Conflict"
    };

    private int RunStatus(Dictionary<string, string?> options)
    {
        var basePath = GetBasePath(options);
        var report = ExportService.Status(basePath, GetOption(options, "layout"));
        if (report.HasErrors)
        {
            WriteErrors(report.Diagnostics);
            return 1;
        }

        var context = report.Context!.Context;
        var layout = report.Layout;
        var statuses = report.Targets;

        _out.WriteLine($"Project: {context.ProjectName}");
        _out.WriteLine($"Layout:  {layout.ToString().ToLowerInvariant()}");

        var rules = context.Rules ?? [];
        if (rules.Count > 0)
        {
            _out.WriteLine($"Rules:   {rules.Count}");
            foreach (var rule in rules)
            {
                var scope = rule.Kind switch
                {
                    RuleKind.Scoped => $"scoped    {string.Join(", ", rule.Paths)}",
                    RuleKind.OnDemand => $"on-demand {rule.Description}",
                    _ => "always on"
                };
                _out.WriteLine($"  {rule.Name,-16} {scope}");
            }
        }

        _out.WriteLine();
        _out.WriteLine($"{"Target",-10}{"Always on",-22}{"Scoped / on-demand",-22}{"Files",-7}State");
        foreach (var status in statuses)
        {
            var onDemand = status.OnDemandChars == 0 ? "-" : FormatSize(status.OnDemandChars);
            _out.WriteLine(
                $"{status.Target,-10}{FormatSize(status.AlwaysOnChars),-22}{onDemand,-22}{status.FileCount,-7}{DescribeState(status.State)}");
        }

        _out.WriteLine();
        _out.WriteLine("Always on = loaded in every request. Scoped / on-demand = loaded only for matching files or when relevant.");
        _out.WriteLine($"Token counts are estimates (~{ExportStatus.CharsPerToken} characters per token).");

        var overlaps = report.Overlaps;
        if (overlaps.Count > 0)
        {
            _out.WriteLine();
            _out.WriteLine("Overlap: these tools read several of the exported files and load them together");
            _out.WriteLine("(from the vendors' documentation; what a tool really loads depends on its version and settings):");
            foreach (var overlap in overlaps)
            {
                _out.WriteLine($"  {overlap.Tool,-18} {string.Join(" + ", overlap.Targets),-27} {FormatSize(overlap.AlwaysOnChars)} always on");
            }

            _out.WriteLine("Tip: export only the targets of the tools you use, or leave out 'agents' when every tool you use has its own format.");
        }

        if (report.NestedAgentsPlan is { } plan)
        {
            _out.WriteLine();
            _out.WriteLine("Nested AGENTS.md:");
            foreach (var (directory, directoryRules) in plan.ByDirectory)
            {
                _out.WriteLine($"  {directory}/AGENTS.md  <- {string.Join(", ", directoryRules.Select(r => r.Name))}");
            }

            foreach (var kept in plan.Kept)
            {
                _out.WriteLine($"  kept in root AGENTS.md: {kept.Name} ({kept.Reason})");
            }
        }

        if (layout == ExportLayout.Single)
        {
            var savings = statuses
                .Where(s => s.AlwaysOnCharsInOtherLayout < s.AlwaysOnChars)
                .Select(s => $"{s.Target} {FormatSize(s.AlwaysOnChars)} -> {FormatSize(s.AlwaysOnCharsInOtherLayout)}")
                .ToList();

            if (savings.Count > 0)
            {
                _out.WriteLine();
                _out.WriteLine("Tip: the 'split' layout (exports.layout) would reduce always-on context:");
                foreach (var saving in savings)
                {
                    _out.WriteLine($"  {saving}");
                }
            }
        }

        return 0;
    }

    private static string FormatSize(int chars) =>
        $"{(chars / 1024.0).ToString("0.0", CultureInfo.InvariantCulture),4} KB (~{ExportStatus.EstimateTokens(chars).ToString("N0", CultureInfo.InvariantCulture)} tok)";

    private static string DescribeState(SyncState state) => state switch
    {
        SyncState.InSync => "in sync",
        SyncState.OutOfDate => "out of date (run export)",
        SyncState.NotExported => "not exported",
        SyncState.Blocked => "blocked (a path leaves the project through a link)",
        _ => "conflict (existing file not generated by aicontext)"
    };

    private string GetBasePath(Dictionary<string, string?> options)
    {
        var path = GetOption(options, "path");
        return string.IsNullOrWhiteSpace(path) ? _workingDirectory : Path.GetFullPath(path, _workingDirectory);
    }

    private static bool IsTrue(Dictionary<string, string?> options, string key)
    {
        if (!options.TryGetValue(key, out var value))
        {
            return false;
        }

        if (string.IsNullOrWhiteSpace(value))
        {
            return true;
        }

        return value.Equals("true", StringComparison.OrdinalIgnoreCase) ||
               value.Equals("1", StringComparison.OrdinalIgnoreCase);
    }

    private static string? GetOption(Dictionary<string, string?> options, string key)
    {
        return options.TryGetValue(key, out var value) ? value : null;
    }

    // Flags are bare (--force); an explicit true/false/1/0 is still accepted. Options that take a value require one.
    private static (Dictionary<string, string?> Values, string? Error) ParseOptions(CommandSpec command, string[] args)
    {
        var values = new Dictionary<string, string?>(StringComparer.OrdinalIgnoreCase);
        for (var i = 0; i < args.Length; i++)
        {
            var arg = args[i];
            if (!arg.StartsWith("--", StringComparison.Ordinal))
            {
                return (values, $"Unknown argument '{arg}'. Only --key [value] is supported.");
            }

            var key = arg[2..];
            if (string.IsNullOrWhiteSpace(key))
            {
                return (values, "Invalid option name.");
            }

            var spec = command.Options.FirstOrDefault(o => o.Name.Equals(key, StringComparison.OrdinalIgnoreCase));
            if (spec is null)
            {
                var valid = string.Join(", ", command.Options.Select(o => $"--{o.Name}"));
                return (values, $"Unknown option '--{key}' for 'aicontext {command.Name}'. Valid options: {valid}.");
            }

            if (values.ContainsKey(spec.Name))
            {
                return (values, $"Option '--{spec.Name}' was specified more than once.");
            }

            var next = i + 1 < args.Length ? args[i + 1] : null;
            string? value = null;
            if (spec.TakesValue)
            {
                if (string.IsNullOrWhiteSpace(next) || next.StartsWith("--", StringComparison.Ordinal))
                {
                    return (values, $"Option '--{spec.Name}' requires a value.");
                }

                value = next;
                i++;
            }
            else if (next is not null && !next.StartsWith("--", StringComparison.Ordinal))
            {
                if (!IsBooleanLiteral(next))
                {
                    return (values, $"Option '--{spec.Name}' does not take a value ('{next}'). Use it without a value, or with true or false.");
                }

                value = next;
                i++;
            }

            values[spec.Name] = value;
        }

        return (values, null);
    }

    private static bool IsBooleanLiteral(string value) =>
        value.Equals("true", StringComparison.OrdinalIgnoreCase) ||
        value.Equals("false", StringComparison.OrdinalIgnoreCase) ||
        value is "1" or "0";

    private static bool IsHelp(string arg)
    {
        return arg is "-h" or "--help" or "help";
    }

    private static bool IsVersion(string arg)
    {
        return arg is "-v" or "--version" or "version";
    }

    private void PrintVersion()
    {
        var informational = System.Reflection.Assembly.GetExecutingAssembly()
            .GetCustomAttributes(typeof(System.Reflection.AssemblyInformationalVersionAttribute), false)
            .OfType<System.Reflection.AssemblyInformationalVersionAttribute>()
            .FirstOrDefault()?.InformationalVersion;
        var version = informational?.Split('+')[0] ?? "unknown";
        _out.WriteLine($"aicontext {version}");
        _out.WriteLine($"Specification version: {ExpectedSpecVersion}");
    }

    private void PrintHelp()
    {
        _out.WriteLine("AIContext CLI");
        _out.WriteLine();
        _out.WriteLine("Usage:");
        foreach (var command in Commands)
        {
            _out.WriteLine($"  {command.Usage}");
        }

        _out.WriteLine("  aicontext --version");

        foreach (var command in Commands)
        {
            _out.WriteLine();
            foreach (var line in command.Help)
            {
                _out.WriteLine(line);
            }
        }

        _out.WriteLine();
        _out.WriteLine("Run 'aicontext <command> --help' for the options of a single command.");
    }

    private void PrintCommandHelp(CommandSpec command)
    {
        _out.WriteLine("Usage:");
        _out.WriteLine($"  {command.Usage}");
        _out.WriteLine();
        foreach (var line in command.Help)
        {
            _out.WriteLine(line);
        }
    }
}
