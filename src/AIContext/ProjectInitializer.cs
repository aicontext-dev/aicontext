using System.Text;
using System.Text.Json;

namespace AIContext;

public enum InitProfile
{
    Core,
    Extended
}

// Created are the files written. Conflicts are files that exist and were not overwritten (no --force, or a file that
// appeared while init was running). Diagnostics explain a refusal: a destination that leaves the project, or enters a
// separate one, through a link (AIC4102, AIC4104); nothing is written then.
public sealed record InitResult(IReadOnlyList<string> Created, IReadOnlyList<string> Conflicts)
{
    public IReadOnlyList<Diagnostic> Diagnostics { get; init; } = [];

    public bool HasErrors => Diagnostics.Any(d => d.IsError);
}

public static class ProjectInitializer
{
    public static bool TryParseProfile(string? value, out InitProfile profile)
    {
        switch (value?.Trim().ToLowerInvariant())
        {
            case null or "" or "core":
                profile = InitProfile.Core;
                return true;
            case "extended":
                profile = InitProfile.Extended;
                return true;
            default:
                profile = InitProfile.Core;
                return false;
        }
    }

    // Hand-written instruction files of the supported tools that already exist, as '/'-separated paths relative to
    // basePath: the main file of every export target, the files in the rule directories of the targets
    // (.github/instructions, .cursor/rules, ...) and nested AGENTS.md files. Files generated by aicontext are not
    // listed. Export never overwrites a main file without force and never touches the other files, so they stay
    // active next to the generated ones, which is why init points them out.
    public static IReadOnlyList<string> FindExistingInstructionFiles(string basePath)
    {
        var found = new List<string>();
        var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var guard = new ExportPathGuard(basePath);

        void Add(string path)
        {
            var full = Path.GetFullPath(path);
            if (File.Exists(full) && seen.Add(full) && guard.FindProblem(full) is null && IsHandWritten(full))
            {
                found.Add(Path.GetRelativePath(basePath, full).Replace('\\', '/'));
            }
        }

        foreach (var target in ExportTargets.All)
        {
            Add(target.ResolvePath(basePath));
        }

        foreach (var target in ExportTargets.All)
        {
            if (target.RuleDirectory is not null)
            {
                var directory = ExportTarget.ResolveRelative(basePath, target.RuleDirectory);
                if (Directory.Exists(directory))
                {
                    foreach (var file in EnumerateFiles(directory, "*" + target.RuleExtension).Order(StringComparer.Ordinal))
                    {
                        Add(file);
                    }
                }
            }

            if (target.NestedFileName is not null)
            {
                foreach (var file in ExportWriter.FindFilesByName(basePath, target.NestedFileName, 0))
                {
                    Add(file);
                }
            }
        }

        return found;
    }

    private static IEnumerable<string> EnumerateFiles(string directory, string pattern)
    {
        try
        {
            return Directory.EnumerateFiles(directory, pattern, SearchOption.AllDirectories).ToList();
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            return [];
        }
    }

    // A file that cannot be read counts as hand-written: it was not generated by aicontext as far as we can tell.
    private static bool IsHandWritten(string path)
    {
        try
        {
            return !ExportWriter.IsGenerated(File.ReadAllText(path));
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            return true;
        }
    }

    // Writes nothing and reports the problem when a destination leaves the project through a link (even with force:
    // force allows overwriting, not writing somewhere else) or when any target file exists and force is not set.
    // Every destination is checked, with the guard that protects export (D12), before the first file is written. A
    // new file is created exclusively, so one that appeared after the check is never overwritten; init then stops
    // and reports it as a conflict (files written before it stay).
    public static InitResult Initialize(
        string basePath,
        string projectName,
        InitProfile profile,
        string schemaUrl,
        string specVersion,
        bool force)
    {
        var contextDirectory = Path.Combine(basePath, ".aicontext");
        var files = BuildFiles(contextDirectory, projectName, profile, schemaUrl, specVersion);

        var guard = new ExportPathGuard(basePath);
        var blocked = new List<Diagnostic>();
        foreach (var path in files.Keys)
        {
            if (guard.FindProblem(path) is { } problem)
            {
                var location = Path.GetRelativePath(basePath, path).Replace('\\', '/');
                blocked.Add(ExportWriter.BlockedDiagnostic(path, problem.Description, problem.Code, location, "Init never writes"));
            }
        }

        if (blocked.Count > 0)
        {
            return new InitResult([], []) { Diagnostics = blocked };
        }

        var existing = files.Keys.Where(File.Exists).ToList();
        if (existing.Count > 0 && !force)
        {
            return new InitResult([], existing);
        }

        Directory.CreateDirectory(contextDirectory);
        var created = new List<string>();
        foreach (var (path, content) in files)
        {
            if (existing.Contains(path))
            {
                File.WriteAllText(path, content, new UTF8Encoding(false));
            }
            else if (!ExportWriter.TryCreateNew(path, content))
            {
                return new InitResult(created, [path]);
            }

            created.Add(path);
        }

        return new InitResult(created, []);
    }

    private static Dictionary<string, string> BuildFiles(
        string contextDirectory,
        string projectName,
        InitProfile profile,
        string schemaUrl,
        string specVersion)
    {
        var contextJson = BuildContextJson(projectName, schemaUrl, specVersion);

        var files = new Dictionary<string, string>
        {
            [Path.Combine(contextDirectory, "README.md")] = ReadmeTemplate(projectName),
            [Path.Combine(contextDirectory, "context.json")] = contextJson + "\n"
        };

        if (profile == InitProfile.Extended)
        {
            files[Path.Combine(contextDirectory, "architecture.md")] = ArchitectureTemplate;
            files[Path.Combine(contextDirectory, "decisions.md")] = DecisionsTemplate;
            files[Path.Combine(contextDirectory, "constraints.md")] = ConstraintsTemplate;
        }

        return files;
    }

    // Utf8JsonWriter instead of JsonSerializer keeps this safe for trimmed binaries.
    private static string BuildContextJson(string projectName, string schemaUrl, string specVersion)
    {
        using var stream = new MemoryStream();
        using (var writer = new Utf8JsonWriter(stream, new JsonWriterOptions { Indented = true, NewLine = "\n" }))
        {
            writer.WriteStartObject();
            writer.WriteString("$schema", schemaUrl);
            writer.WriteString("specVersion", specVersion);
            writer.WriteStartObject("project");
            writer.WriteString("name", projectName);
            writer.WriteEndObject();
            writer.WriteEndObject();
        }

        return Encoding.UTF8.GetString(stream.ToArray());
    }

    private static string ReadmeTemplate(string projectName) =>
        $"# Project: {projectName}\n\nBrief project summary.\n\n**Tech stack:** TODO  \n**Architecture:** TODO  \n**Testing:** TODO\n";

    private const string ArchitectureTemplate =
        "## Overview\n\nTODO: describe the main components and how they interact.\n\n## Layers and boundaries\n\nTODO: which code may depend on which, and why.\n";

    private const string DecisionsTemplate =
        "Format: context, decision, consequence. Newest decisions last.\n\n### D1. TODO: title of the first decision\n**Context:** TODO\n**Decision:** TODO\n**Consequence:** TODO\n";

    private const string ConstraintsTemplate =
        "Hard rules for AI assistants and contributors.\n\n- TODO: a rule that must never be violated.\n";
}
