using System.Security.Cryptography;
using System.Text;

namespace AIContext;

// Blocked: the file must not or cannot be written or removed, so the export is refused before anything is written.
// Reason says why and ReasonCode is the matching diagnostic code: the path resolves outside the project, or into a
// separate project, through a symlink or junction (D11, D12); a directory is where the file has to go; the existing
// file cannot be read.
public enum ExportFileStatus
{
    Created,
    Updated,
    Unchanged,
    // A previously generated rule file whose source no longer exists.
    Deleted,
    // Existing file that was not generated by aicontext; only overwritten with force.
    Conflict,
    Blocked
}

// ExistingHash is the SHA-256 of the file as it was when it was planned (null when it did not exist). Apply
// compares it with the file on disk, so a plan that went stale is refused instead of overwriting newer content.
// For a Blocked file, Reason says why and ReasonCode is the matching diagnostic code.
public sealed record ExportFilePlan(
    string Target,
    string Path,
    string Content,
    ExportFileStatus Status,
    string? Reason = null,
    string? ExistingHash = null,
    string? ReasonCode = null);

// Thrown when a file is no longer in the state it was planned for: it appeared between the check and the write of a
// new file, or an existing file changed before it was replaced.
public sealed class StaleExportPlanException : IOException
{
    public StaleExportPlanException(string path)
        : this(path, "was created after the export was planned")
    {
    }

    public StaleExportPlanException(string path, string reason)
        : base($"{path} {reason}.")
    {
        FilePath = path;
        Reason = reason;
    }

    public string FilePath { get; }

    // Completes the sentence "<path> ...".
    public string Reason { get; }
}

public static class ExportWriter
{
    private const int HeaderLinesToScan = 10;

    // Plans every file of a target: its outputs plus removal of generated rule files that are no longer produced.
    public static IReadOnlyList<ExportFilePlan> PlanTarget(
        ExportTarget target,
        string basePath,
        ExportContext exportContext,
        ExportLayout layout,
        bool force,
        RenderOptions? options = null)
    {
        var outputs = target.Render(exportContext, layout, options);
        var plans = new List<ExportFilePlan>();
        var produced = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var guard = new ExportPathGuard(basePath);

        foreach (var output in outputs)
        {
            var path = ExportTarget.ResolveRelative(basePath, output.RelativePath);
            produced.Add(System.IO.Path.GetFullPath(path));
            plans.Add(PlanFile(guard, target.Name, path, output.Content, force));
        }

        plans.AddRange(PlanOrphans(guard, target, basePath, produced));
        plans.AddRange(PlanNestedOrphans(guard, target, basePath, produced));
        return plans;
    }

    public static ExportFilePlan Plan(ExportTarget target, string basePath, ExportContext exportContext, bool force)
    {
        var output = target.Render(exportContext, ExportLayout.Single)[0];
        return PlanFile(new ExportPathGuard(basePath), target.Name, ExportTarget.ResolveRelative(basePath, output.RelativePath), output.Content, force);
    }

    // Writes one planned file; ExportService.Apply verifies the whole plan before it calls this.
    // - Created: the file is created exclusively, so a file that appeared after planning is never overwritten, and
    //   one that is only partly written is removed again.
    // - Updated: the file is replaced through a temporary file, so a failure leaves the old content intact.
    // - Deleted: the file is removed.
    // An expected I/O failure (locked, no permission, no space) is thrown as IOException or
    // UnauthorizedAccessException; ExportService.Apply reports it as a diagnostic with the files already written.
    public static void Apply(ExportFilePlan plan)
    {
        switch (plan.Status)
        {
            case ExportFileStatus.Created:
                if (!TryCreateNew(plan.Path, plan.Content))
                {
                    throw new StaleExportPlanException(plan.Path);
                }

                break;
            case ExportFileStatus.Updated:
                ReplaceExisting(plan.Path, plan.Content, plan.ExistingHash);
                break;
            case ExportFileStatus.Deleted:
                File.Delete(plan.Path);
                break;
        }
    }

    // Creates a file that must not exist yet (FileMode.CreateNew, so whatever is there, even a dangling link, is
    // never overwritten or followed). Returns false when the path is taken. Shared by export and init: every new
    // file of aicontext is created this way. If writing fails after the file was created, the incomplete file (it is
    // ours: this call created it) is removed again before the failure is thrown. afterWritten is a seam for tests.
    internal static bool TryCreateNew(string path, string content, Action? afterWritten = null)
    {
        Directory.CreateDirectory(System.IO.Path.GetDirectoryName(path)!);
        FileStream stream;
        try
        {
            stream = new FileStream(path, FileMode.CreateNew, FileAccess.Write);
        }
        catch (IOException) when (File.Exists(path))
        {
            return false;
        }

        try
        {
            using (stream)
            {
                stream.Write(new UTF8Encoding(false).GetBytes(content));
                stream.Flush(flushToDisk: true);
            }

            afterWritten?.Invoke();
            return true;
        }
        catch (Exception ex)
        {
            if (CleanUp(ex, path) is { } failure)
            {
                throw failure;
            }

            throw;
        }
    }

    // Replaces an existing file so that a failure never leaves it half-written: the new content is written to a
    // temporary file in the same directory and swapped in, and the temporary file is removed if anything fails. The
    // swap must not change what the destination means, so before it:
    // - a link is not replaced (that would put a regular file where the link was and change where the content
    //   lands); it is overwritten in place, as before, and an interrupted write can leave it incomplete;
    // - the file must be writable as it is (permission, not locked): a read-only file in a writable directory is not
    //   replaced, and nothing is truncated to find out;
    // - the permission bits of the old file are kept on Unix (the owner, ACLs and extended attributes of the old file
    //   are not carried over; a hard link to the old file is no longer the same file afterwards);
    // - when expectedHash is given, the file must still have that content right before the swap (the stale-plan
    //   check again, with a much shorter gap than the one before the first write).
    // afterTemporaryFileWritten is a seam for tests.
    internal static void ReplaceExisting(string path, string content, string? expectedHash = null, Action? afterTemporaryFileWritten = null)
    {
        var bytes = new UTF8Encoding(false).GetBytes(content);
        if (IsLink(path))
        {
            File.WriteAllBytes(path, bytes);
            return;
        }

        ProbeWrite(path);
        var temporary = System.IO.Path.Combine(
            System.IO.Path.GetDirectoryName(path)!,
            $".{System.IO.Path.GetFileName(path)}.{Guid.NewGuid():N}.tmp");

        try
        {
            using (var stream = new FileStream(temporary, FileMode.CreateNew, FileAccess.Write, FileShare.None))
            {
                stream.Write(bytes);
                stream.Flush(flushToDisk: true);
            }

            afterTemporaryFileWritten?.Invoke();

            if (!OperatingSystem.IsWindows())
            {
                File.SetUnixFileMode(temporary, File.GetUnixFileMode(path));
            }

            if (expectedHash is not null && !string.Equals(HashOf(File.ReadAllBytes(path)), expectedHash, StringComparison.Ordinal))
            {
                throw new StaleExportPlanException(path, "changed after the export was planned");
            }

            File.Replace(temporary, path, destinationBackupFileName: null);
        }
        catch (Exception ex)
        {
            if (CleanUp(ex, temporary) is { } failure)
            {
                throw failure;
            }

            throw;
        }
    }

    // Removes a file this call created and that must not stay behind. Returns null when the original failure is to be
    // rethrown as it is. When the removal failed too and the original failure is an expected I/O one, returns the
    // same failure with the leftover named so that the user can delete it by hand. A bug (any other exception) and a
    // stale-plan refusal are never rewrapped.
    private static Exception? CleanUp(Exception failure, string leftover)
    {
        try
        {
            File.Delete(leftover);
            return null;
        }
        catch (Exception cleanup) when (cleanup is IOException or UnauthorizedAccessException)
        {
            var expected = failure is (IOException or UnauthorizedAccessException) && failure is not StaleExportPlanException;
            return expected
                ? new IOException($"{failure.Message} The leftover file '{leftover}' could not be removed ({cleanup.Message}); delete it by hand.", failure)
                : null;
        }
    }

    private static bool IsLink(string path)
    {
        var info = new FileInfo(path);
        return info.LinkTarget is not null || (info.Attributes & FileAttributes.ReparsePoint) != 0;
    }

    // Opens an existing file for writing without changing it: fails when it is read-only, locked by another program
    // or the account has no permission.
    private static void ProbeWrite(string path)
    {
        using (new FileStream(path, FileMode.Open, FileAccess.Write, FileShare.ReadWrite | FileShare.Delete))
        {
        }
    }

    // Null when the existing file could be written as it is; otherwise why not. Nothing is written or truncated.
    internal static string? FindWriteBlock(string path)
    {
        try
        {
            ProbeWrite(path);
            return null;
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            return ex.Message;
        }
    }

    // Null when the file may still be written as planned; otherwise the reason it must not be: its path now
    // leaves the project through a link, the file is not in the state it was planned for, it cannot be read or
    // written, or a directory is in its way. Nothing is changed here, so everything that can be known is known
    // before the first file is written.
    internal static Diagnostic? Verify(ExportFilePlan plan, ExportPathGuard guard, string basePath)
    {
        if (plan.Status is not (ExportFileStatus.Created or ExportFileStatus.Updated or ExportFileStatus.Deleted))
        {
            return null;
        }

        var location = System.IO.Path.GetRelativePath(basePath, plan.Path).Replace('\\', '/');
        var problem = guard.FindProblem(plan.Path);
        if (problem is not null)
        {
            return BlockedDiagnostic(plan.Path, problem.Description, problem.Code, location);
        }

        string? current;
        try
        {
            current = File.Exists(plan.Path) ? HashOf(File.ReadAllBytes(plan.Path)) : null;
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            return BlockedDiagnostic(plan.Path, $"could not be read again ({ex.Message})", DiagnosticCodes.FileAccessFailed, location);
        }

        if (!string.Equals(current, plan.ExistingHash, StringComparison.Ordinal))
        {
            return StalePlan(
                plan.Path,
                location,
                plan.ExistingHash is null ? "was created after the export was planned" : "changed or was removed after the export was planned");
        }

        problem = plan.Status == ExportFileStatus.Created ? guard.FindCollision(plan.Path) : null;
        if (problem is not null)
        {
            return BlockedDiagnostic(plan.Path, problem.Description, problem.Code, location);
        }

        return plan.Status == ExportFileStatus.Updated && FindWriteBlock(plan.Path) is { } cannotWrite
            ? BlockedDiagnostic(plan.Path, $"cannot be written ({cannotWrite})", DiagnosticCodes.FileAccessFailed, location)
            : null;
    }

    // refusal starts the sentence that says what is never done; init words it for itself.
    internal static Diagnostic BlockedDiagnostic(
        string path,
        string? reason,
        string? code,
        string location,
        string refusal = "Export never writes or deletes") =>
        code switch
        {
            DiagnosticCodes.PathInSeparateProject => Diagnostic.Error(
                code,
                $"{path} {reason}. {refusal} files of a separate project.",
                location),
            DiagnosticCodes.DestinationNotAFile => Diagnostic.Error(
                code,
                $"{path} {reason}. Move or remove it, then run the command again.",
                location),
            DiagnosticCodes.FileAccessFailed => Diagnostic.Error(
                code,
                $"{path} {reason}. Check that no other program has it locked and that you have permission, then run the command again.",
                location),
            _ => Diagnostic.Error(
                DiagnosticCodes.PathOutsideProject,
                $"{path} {reason}. {refusal} outside the project.",
                location)
        };

    // A write or removal that failed after the plan had been verified: what was written before stays written.
    internal static Diagnostic WriteFailed(ExportFilePlan plan, Exception failure, string basePath) =>
        WriteFailed(plan.Path, plan.Status == ExportFileStatus.Deleted ? "removed" : "written", failure, basePath);

    internal static Diagnostic WriteFailed(string path, string verb, Exception failure, string basePath) =>
        Diagnostic.Error(
            DiagnosticCodes.FileAccessFailed,
            $"{path} could not be {verb} ({failure.Message}). " +
            "Check that no other program has it locked, that you have permission and that there is enough free space, then run the command again.",
            System.IO.Path.GetRelativePath(basePath, path).Replace('\\', '/'));

    internal static Diagnostic StalePlan(string path, string location, string reason) =>
        Diagnostic.Error(
            DiagnosticCodes.StaleExportPlan,
            $"{path} {reason}. The export plan is out of date; plan the export again.",
            location);

    private static string HashOf(byte[] bytes) => Convert.ToHexString(SHA256.HashData(bytes));

    // Same decoding as File.ReadAllText (UTF-8, byte order mark honored), so the text and the hash come from one read.
    private static string DecodeText(byte[] bytes)
    {
        using var reader = new StreamReader(new MemoryStream(bytes), new UTF8Encoding(false), detectEncodingFromByteOrderMarks: true);
        return reader.ReadToEnd();
    }

    public static bool IsGenerated(string content)
    {
        return ContextExporter.NormalizeLineEndings(content)
            .Split('\n')
            .Take(HeaderLinesToScan)
            .Any(line => line.Contains(ContextExporter.GeneratedMarker, StringComparison.Ordinal));
    }

    private static ExportFilePlan PlanFile(ExportPathGuard guard, string targetName, string path, string content, bool force)
    {
        var blocked = Blocked(guard, targetName, path);
        if (blocked is not null)
        {
            return blocked;
        }

        try
        {
            if (!File.Exists(path))
            {
                return new ExportFilePlan(targetName, path, content, ExportFileStatus.Created);
            }

            var bytes = File.ReadAllBytes(path);
            var existing = DecodeText(bytes);
            if (string.Equals(ContextExporter.NormalizeLineEndings(existing), content, StringComparison.Ordinal))
            {
                return new ExportFilePlan(targetName, path, content, ExportFileStatus.Unchanged);
            }

            var status = force || IsGenerated(existing) ? ExportFileStatus.Updated : ExportFileStatus.Conflict;
            return new ExportFilePlan(targetName, path, content, status, ExistingHash: HashOf(bytes));
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            return Unreadable(targetName, path, ex);
        }
    }

    // An existing file that cannot be read cannot be compared, so the export is refused instead of guessing.
    private static ExportFilePlan Unreadable(string targetName, string path, Exception failure) =>
        new(targetName, path, string.Empty, ExportFileStatus.Blocked, $"could not be read ({failure.Message})", ReasonCode: DiagnosticCodes.FileAccessFailed);

    // Checked before the file is read, so nothing outside the project is even opened. A directory where the file has
    // to go (or a file where a directory has to be) is a problem as well: it is known now, so no file is written.
    private static ExportFilePlan? Blocked(ExportPathGuard guard, string targetName, string path)
    {
        var problem = guard.FindWriteProblem(path);
        return problem is null
            ? null
            : new ExportFilePlan(targetName, path, string.Empty, ExportFileStatus.Blocked, problem.Description, ReasonCode: problem.Code);
    }

    // Nested files (for example src/ui/AGENTS.md) can be anywhere in the repository, so the tree is walked,
    // skipping hidden and dependency/build directories and every directory that is a separate project (D11).
    // Only files with the generated header are removed.
    private static IEnumerable<ExportFilePlan> PlanNestedOrphans(ExportPathGuard guard, ExportTarget target, string basePath, HashSet<string> produced)
    {
        if (target.NestedFileName is null)
        {
            yield break;
        }

        foreach (var file in FindFilesByName(basePath, target.NestedFileName, 0))
        {
            if (produced.Contains(System.IO.Path.GetFullPath(file)))
            {
                continue;
            }

            var blocked = Blocked(guard, target.Name, file);
            if (blocked is not null)
            {
                yield return blocked;
            }
            else if (PlanDeletion(target.Name, file) is { } deletion)
            {
                yield return deletion;
            }
        }
    }

    private static readonly HashSet<string> SkippedDirectories = new(StringComparer.OrdinalIgnoreCase)
    {
        "node_modules", "bin", "obj", "vendor", "dist", "build", "target", "venv", "__pycache__"
    };

    private const int MaxWalkDepth = 12;

    internal static IEnumerable<string> FindFilesByName(string directory, string fileName, int depth)
    {
        if (depth > 0)
        {
            var candidate = System.IO.Path.Combine(directory, fileName);
            if (File.Exists(candidate))
            {
                yield return candidate;
            }
        }

        if (depth >= MaxWalkDepth)
        {
            yield break;
        }

        IEnumerable<string> children;
        try
        {
            children = Directory.EnumerateDirectories(directory).OrderBy(d => d, StringComparer.Ordinal).ToList();
        }
        catch (Exception ex) when (ex is UnauthorizedAccessException or IOException)
        {
            yield break;
        }

        foreach (var child in children)
        {
            var name = System.IO.Path.GetFileName(child);
            if (name.StartsWith('.') ||
                SkippedDirectories.Contains(name) ||
                new DirectoryInfo(child).Attributes.HasFlag(FileAttributes.ReparsePoint) ||
                ProjectBoundary.IsProjectRoot(child))
            {
                continue;
            }

            foreach (var file in FindFilesByName(child, fileName, depth + 1))
            {
                yield return file;
            }
        }
    }

    // Only files that carry the generated header and the aicontext- prefix are ever removed.
    private static IEnumerable<ExportFilePlan> PlanOrphans(ExportPathGuard guard, ExportTarget target, string basePath, HashSet<string> produced)
    {
        if (target.RuleDirectory is null)
        {
            yield break;
        }

        var directory = ExportTarget.ResolveRelative(basePath, target.RuleDirectory);
        if (!Directory.Exists(directory))
        {
            yield break;
        }

        List<string> candidates;
        string? listingFailure = null;
        try
        {
            candidates = Directory.EnumerateFiles(directory)
                .Where(f =>
                {
                    var name = System.IO.Path.GetFileName(f);
                    return name.StartsWith(ExportTargets.GeneratedRulePrefix, StringComparison.Ordinal) &&
                           name.EndsWith(target.RuleExtension, StringComparison.Ordinal);
                })
                .OrderBy(f => f, StringComparer.Ordinal)
                .ToList();
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            candidates = [];
            listingFailure = ex.Message;
        }

        if (listingFailure is not null)
        {
            // Which generated files are left over cannot be known, so the export is refused.
            yield return new ExportFilePlan(
                target.Name,
                directory,
                string.Empty,
                ExportFileStatus.Blocked,
                $"could not be listed ({listingFailure})",
                ReasonCode: DiagnosticCodes.FileAccessFailed);
            yield break;
        }

        foreach (var file in candidates)
        {
            if (produced.Contains(System.IO.Path.GetFullPath(file)))
            {
                continue;
            }

            var blocked = Blocked(guard, target.Name, file);
            if (blocked is not null)
            {
                yield return blocked;
            }
            else if (PlanDeletion(target.Name, file) is { } deletion)
            {
                yield return deletion;
            }
        }
    }

    // Only a file that still carries the generated header is removed; the hash lets Apply notice a later change.
    // A file that cannot be read cannot be told from a generated one, so it blocks the export.
    private static ExportFilePlan? PlanDeletion(string targetName, string file)
    {
        try
        {
            var bytes = File.ReadAllBytes(file);
            return IsGenerated(DecodeText(bytes))
                ? new ExportFilePlan(targetName, file, string.Empty, ExportFileStatus.Deleted, ExistingHash: HashOf(bytes))
                : null;
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            return Unreadable(targetName, file, ex);
        }
    }
}
