using System.Security.Cryptography;
using System.Text;

namespace AIContext;

public static class ContextExporter
{
    public const string GeneratedMarker = "Auto-generated by aicontext export";

    private sealed record Item(
        string Id,
        string Title,
        string Body,
        string? Description,
        IReadOnlyList<string> Paths,
        RuleKind Kind,
        bool IsRule);

    public static string BuildAgents(ExportContext exportContext) => Single("agents", exportContext);

    public static string BuildCopilot(ExportContext exportContext) => Single("copilot", exportContext);

    public static string BuildClaude(ExportContext exportContext) => Single("claude", exportContext);

    public static string BuildWindsurf(ExportContext exportContext) => Single("windsurf", exportContext);

    public static string BuildDevin(ExportContext exportContext) => Single("devin", exportContext);

    public static string BuildAider(ExportContext exportContext) => Single("aider", exportContext);

    public static string BuildCursor(ExportContext exportContext) => Single("cursor", exportContext);

    // Renders every file a target produces. The first output is always the target's main file.
    public static IReadOnlyList<ExportOutput> Render(
        ExportTarget target,
        ExportContext exportContext,
        ExportLayout layout,
        RenderOptions? options = null)
    {
        var split = layout == ExportLayout.Split && target.Style != RuleStyle.None && target.RuleDirectory is not null;
        var hash = ComputeSourceHash(exportContext);

        var nested = layout == ExportLayout.Split &&
                     target.NestedFileName is not null &&
                     options is { NestedAgents: true, BasePath: not null }
            ? NestedAgentsPlanner.Plan(exportContext.Rules ?? [], options.BasePath)
            : null;

        var mainItems = new List<Item>();
        var fileItems = new List<Item>();
        foreach (var item in BuildItems(exportContext))
        {
            if (nested is not null && item.IsRule && nested.NestedRuleNames.Contains(item.Id))
            {
                continue;
            }

            var separate = split &&
                           (item.Kind == RuleKind.Scoped ||
                            (item.Kind == RuleKind.OnDemand && SupportsOnDemand(target.Style)));
            (separate ? fileItems : mainItems).Add(item);
        }

        var outputs = new List<ExportOutput>
        {
            new(target.RelativePath, BuildMain(target, exportContext, hash, mainItems, split))
        };

        foreach (var item in fileItems)
        {
            var path = $"{target.RuleDirectory}/{ExportTargets.GeneratedRulePrefix}{item.Id}{target.RuleExtension}";
            if (item.Kind != RuleKind.Scoped)
            {
                outputs.Add(new ExportOutput(path, BuildRuleFile(target, hash, item, [])));
                continue;
            }

            // A scoped rule is written for a tool only with the scope its author wrote; otherwise nothing is written
            // (not even a fallback into the main file, which would load it for the whole project).
            var scope = ScopeTranslator.Translate(target, item.Id, item.Paths);
            outputs.Add(scope.Problem is null
                ? new ExportOutput(path, BuildRuleFile(target, hash, item, scope.Patterns))
                : new ExportOutput(path, string.Empty, scope.Problem));
        }

        if (nested is not null)
        {
            foreach (var (directory, rules) in nested.ByDirectory)
            {
                outputs.Add(new ExportOutput($"{directory}/{target.NestedFileName}", BuildNestedFile(target, hash, directory, rules)));
            }
        }

        return outputs;
    }

    private static string BuildNestedFile(ExportTarget target, string hash, string directory, IReadOnlyList<RuleDocument> rules)
    {
        var builder = new StringBuilder();
        AppendHeader(builder, target.Name, hash);
        AppendLine(builder, $"# Rules for {directory}");

        foreach (var rule in rules.OrderBy(r => r.Name, StringComparer.Ordinal))
        {
            AppendLine(builder, string.Empty);
            AppendLine(builder, $"## Rule: {rule.Name}");
            AppendLine(builder, Clean(rule.Body));
        }

        return builder.ToString().TrimEnd() + "\n";
    }

    // Hash of the normalized sources, so output is identical across OSes and line-ending settings.
    public static string ComputeSourceHash(ExportContext exportContext)
    {
        var parts = new List<string>
        {
            exportContext.ProjectName,
            NormalizeReadmeForAgents(exportContext.ReadmeContent),
            Clean(exportContext.Architecture),
            Clean(exportContext.Decisions),
            Clean(exportContext.Patterns),
            Clean(exportContext.Constraints),
            Clean(exportContext.Glossary)
        };

        foreach (var rule in exportContext.Rules ?? [])
        {
            parts.Add($"rule:{rule.Name}");
            parts.Add(rule.Description ?? string.Empty);
            parts.Add(string.Join('\n', rule.Paths));
            parts.Add(Clean(rule.Body));
        }

        var bytes = Encoding.UTF8.GetBytes(string.Join('\0', parts));
        return Convert.ToHexString(SHA256.HashData(bytes))[..16].ToLowerInvariant();
    }

    private static string Single(string targetName, ExportContext exportContext) =>
        ExportTargets.Find(targetName)!.Build(exportContext);

    // Tools that can load a rule by its description. Others keep on-demand content inline.
    private static bool SupportsOnDemand(RuleStyle style) => style is RuleStyle.Cursor or RuleStyle.Windsurf;

    private static IReadOnlyList<Item> BuildItems(ExportContext exportContext)
    {
        var name = exportContext.ProjectName;
        var items = new List<Item>();

        AddBuiltIn(items, "architecture", "Architecture", exportContext.Architecture,
            $"Architecture and design rationale for {name}", RuleKind.OnDemand);
        AddBuiltIn(items, "decisions", "Key Decisions", exportContext.Decisions,
            $"Key decisions and trade-offs for {name}", RuleKind.OnDemand);
        AddBuiltIn(items, "patterns", "Coding Patterns", exportContext.Patterns,
            $"Preferred coding patterns for {name}", RuleKind.OnDemand);
        AddBuiltIn(items, "constraints", "Constraints", exportContext.Constraints, null, RuleKind.Always);
        AddBuiltIn(items, "glossary", "Glossary", exportContext.Glossary,
            $"Domain glossary for {name}", RuleKind.OnDemand);

        foreach (var rule in (exportContext.Rules ?? []).OrderBy(r => r.Name, StringComparer.Ordinal))
        {
            items.Add(new Item(rule.Name, $"Rule: {rule.Name}", Clean(rule.Body), rule.Description, rule.Paths, rule.Kind, true));
        }

        return items;
    }

    private static void AddBuiltIn(List<Item> items, string id, string title, string? content, string? description, RuleKind kind)
    {
        var body = Clean(content);
        if (body.Length > 0)
        {
            items.Add(new Item(id, title, body, description, [], kind, false));
        }
    }

    private static string BuildMain(
        ExportTarget target,
        ExportContext exportContext,
        string hash,
        IReadOnlyList<Item> items,
        bool split)
    {
        var builder = new StringBuilder();

        if (target.Style == RuleStyle.Cursor)
        {
            var cursorDescription = split
                ? $"Core project context and constraints for {exportContext.ProjectName}"
                : $"Project constraints and patterns for {exportContext.ProjectName}";

            AppendLine(builder, "---");
            AppendLine(builder, $"description: {Quote(cursorDescription)}");
            AppendLine(builder, "alwaysApply: true");
            AppendLine(builder, "---");
            AppendLine(builder, string.Empty);
        }
        else if (target.Style == RuleStyle.Windsurf && (split || target.AlwaysOnTriggerInSingleLayout))
        {
            AppendLine(builder, "---");
            AppendLine(builder, "trigger: always_on");
            AppendLine(builder, "---");
            AppendLine(builder, string.Empty);
        }

        AppendHeader(builder, target.Name, hash);

        var title = MainTitle(target.Name, exportContext.ProjectName);
        if (title is not null)
        {
            AppendLine(builder, $"# {title}");
            AppendLine(builder, string.Empty);
        }

        AppendLine(builder, NormalizeReadmeForAgents(exportContext.ReadmeContent));

        foreach (var item in items)
        {
            AppendLine(builder, string.Empty);
            AppendLine(builder, $"## {item.Title}");

            var hint = ScopeHint(item);
            if (hint is not null)
            {
                AppendLine(builder, hint);
                AppendLine(builder, string.Empty);
            }

            AppendLine(builder, item.Body);
        }

        return builder.ToString().TrimEnd() + "\n";
    }

    private static string BuildRuleFile(ExportTarget target, string hash, Item item, IReadOnlyList<string> patterns)
    {
        var builder = new StringBuilder();
        var globs = string.Join(',', patterns);
        var scoped = item.Kind == RuleKind.Scoped;
        var description = string.IsNullOrWhiteSpace(item.Description) ? null : item.Description;

        AppendLine(builder, "---");
        switch (target.Style)
        {
            case RuleStyle.Cursor:
                if (description is not null)
                {
                    AppendLine(builder, $"description: {Quote(description)}");
                }

                if (scoped)
                {
                    // Cursor documents unquoted, comma-separated globs.
                    AppendLine(builder, $"globs: {globs}");
                }

                AppendLine(builder, "alwaysApply: false");
                break;
            case RuleStyle.Copilot:
                AppendLine(builder, $"applyTo: {Quote(globs)}");
                if (description is not null)
                {
                    AppendLine(builder, $"description: {Quote(description)}");
                }

                break;
            case RuleStyle.Claude:
                AppendLine(builder, "paths:");
                foreach (var path in patterns)
                {
                    AppendLine(builder, $"  - {Quote(path)}");
                }

                break;
            default:
                AppendLine(builder, $"trigger: {(scoped ? "glob" : "model_decision")}");
                if (scoped)
                {
                    AppendLine(builder, $"globs: {Quote(globs)}");
                }

                if (description is not null)
                {
                    AppendLine(builder, $"description: {Quote(description)}");
                }

                break;
        }

        AppendLine(builder, "---");
        AppendLine(builder, string.Empty);
        AppendHeader(builder, target.Name, hash);
        AppendLine(builder, $"# {item.Title}");
        AppendLine(builder, string.Empty);
        AppendLine(builder, item.Body);

        return builder.ToString().TrimEnd() + "\n";
    }

    private static string? ScopeHint(Item item)
    {
        if (!item.IsRule)
        {
            return null;
        }

        return item.Kind switch
        {
            RuleKind.Scoped => $"Applies to: {string.Join(", ", item.Paths.Select(p => $"`{p}`"))}",
            RuleKind.OnDemand => $"Use when: {item.Description}",
            _ => null
        };
    }

    private static string? MainTitle(string targetName, string projectName) => targetName switch
    {
        "agents" => projectName,
        "copilot" => $"Copilot Instructions for {projectName}",
        "claude" => $"CLAUDE Instructions for {projectName}",
        "windsurf" => $"Windsurf Rules for {projectName}",
        "devin" => $"Devin Rules for {projectName}",
        "aider" => $"Aider Conventions for {projectName}",
        _ => null
    };

    private static void AppendHeader(StringBuilder builder, string targetName, string hash)
    {
        AppendLine(builder, $"<!-- {GeneratedMarker} --target {targetName} -->");
        AppendLine(builder, $"<!-- Source: .aicontext/ | Source-hash: sha256:{hash} | Do not edit directly -->");
        AppendLine(builder, string.Empty);
    }

    private static string NormalizeReadmeForAgents(string readmeContent)
    {
        var lines = NormalizeLineEndings(readmeContent)
            .Split('\n')
            .ToList();

        if (lines.Count > 0 && lines[0].StartsWith("# ", StringComparison.Ordinal))
        {
            lines.RemoveAt(0);
            while (lines.Count > 0 && string.IsNullOrWhiteSpace(lines[0]))
            {
                lines.RemoveAt(0);
            }
        }

        return string.Join('\n', lines).Trim();
    }

    private static string Clean(string? content) =>
        content is null ? string.Empty : NormalizeLineEndings(content).Trim();

    internal static string NormalizeLineEndings(string value) =>
        value.Replace("\r\n", "\n", StringComparison.Ordinal);

    // Always LF, so output does not depend on Environment.NewLine.
    private static void AppendLine(StringBuilder builder, string line) =>
        builder.Append(line).Append('\n');

    private static string Quote(string value) =>
        "\"" + value.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal) + "\"";
}
