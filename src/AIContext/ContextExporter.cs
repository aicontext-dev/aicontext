using System.Security.Cryptography;
using System.Text;

namespace AIContext;

public static class ContextExporter
{
    public const string GeneratedMarker = "Auto-generated by aicontext export";

    public static string BuildAgents(ExportContext exportContext) =>
        Build(exportContext, "agents", exportContext.ProjectName);

    public static string BuildCopilot(ExportContext exportContext) =>
        Build(exportContext, "copilot", $"Copilot Instructions for {exportContext.ProjectName}");

    public static string BuildClaude(ExportContext exportContext) =>
        Build(exportContext, "claude", $"CLAUDE Instructions for {exportContext.ProjectName}");

    public static string BuildWindsurf(ExportContext exportContext) =>
        Build(exportContext, "windsurf", $"Windsurf Rules for {exportContext.ProjectName}");

    public static string BuildAider(ExportContext exportContext) =>
        Build(exportContext, "aider", $"Aider Conventions for {exportContext.ProjectName}");

    public static string BuildCursor(ExportContext exportContext) =>
        Build(exportContext, "cursor", title: null);

    // Hash of the normalized sources, so output is identical across OSes and line-ending settings.
    public static string ComputeSourceHash(ExportContext exportContext)
    {
        var parts = new[]
        {
            exportContext.ProjectName,
            NormalizeReadmeForAgents(exportContext.ReadmeContent),
            Clean(exportContext.Architecture),
            Clean(exportContext.Decisions),
            Clean(exportContext.Patterns),
            Clean(exportContext.Constraints),
            Clean(exportContext.Glossary)
        };

        var bytes = Encoding.UTF8.GetBytes(string.Join('\0', parts));
        return Convert.ToHexString(SHA256.HashData(bytes))[..16].ToLowerInvariant();
    }

    private static string Build(ExportContext exportContext, string target, string? title)
    {
        var builder = new StringBuilder();

        if (target == "cursor")
        {
            AppendLine(builder, "---");
            AppendLine(builder, $"description: \"Project constraints and patterns for {EscapeYamlDoubleQuoted(exportContext.ProjectName)}\"");
            AppendLine(builder, "alwaysApply: true");
            AppendLine(builder, "---");
            AppendLine(builder, string.Empty);
        }

        AppendLine(builder, $"<!-- {GeneratedMarker} --target {target} -->");
        AppendLine(builder, $"<!-- Source: .aicontext/ | Source-hash: sha256:{ComputeSourceHash(exportContext)} | Do not edit directly -->");
        AppendLine(builder, string.Empty);

        if (title is not null)
        {
            AppendLine(builder, $"# {title}");
            AppendLine(builder, string.Empty);
        }

        AppendLine(builder, NormalizeReadmeForAgents(exportContext.ReadmeContent));

        AppendSection(builder, "Architecture", exportContext.Architecture);
        AppendSection(builder, "Key Decisions", exportContext.Decisions);
        AppendSection(builder, "Coding Patterns", exportContext.Patterns);
        AppendSection(builder, "Constraints", exportContext.Constraints);
        AppendSection(builder, "Glossary", exportContext.Glossary);

        return builder.ToString().TrimEnd() + "\n";
    }

    private static string NormalizeReadmeForAgents(string readmeContent)
    {
        var lines = NormalizeLineEndings(readmeContent)
            .Split('\n')
            .ToList();

        if (lines.Count > 0 && lines[0].StartsWith("# ", StringComparison.Ordinal))
        {
            lines.RemoveAt(0);
            while (lines.Count > 0 && string.IsNullOrWhiteSpace(lines[0]))
            {
                lines.RemoveAt(0);
            }
        }

        return string.Join('\n', lines).Trim();
    }

    private static void AppendSection(StringBuilder builder, string title, string? content)
    {
        var cleaned = Clean(content);
        if (cleaned.Length == 0)
        {
            return;
        }

        AppendLine(builder, string.Empty);
        AppendLine(builder, $"## {title}");
        AppendLine(builder, cleaned);
    }

    private static string Clean(string? content) =>
        content is null ? string.Empty : NormalizeLineEndings(content).Trim();

    internal static string NormalizeLineEndings(string value) =>
        value.Replace("\r\n", "\n", StringComparison.Ordinal);

    // Always LF, so output does not depend on Environment.NewLine.
    private static void AppendLine(StringBuilder builder, string line) =>
        builder.Append(line).Append('\n');

    private static string EscapeYamlDoubleQuoted(string value)
    {
        return value.Replace("\\", "\\\\", StringComparison.Ordinal)
            .Replace("\"", "\\\"", StringComparison.Ordinal);
    }
}
