namespace AIContext;

// How a tool expresses scoped (path-based) and on-demand (description-based) rules.
public enum RuleStyle
{
    // No native rule scoping (single file only).
    None,
    Cursor,
    Copilot,
    Claude,
    // Windsurf and Devin share the same rule format (trigger/globs/description frontmatter).
    Windsurf
}

// Problem is set instead of Content when the file cannot be generated without giving a rule a different scope than
// its author wrote (a pattern the tool cannot be told, see ScopeTranslator); the planner then blocks the export.
public sealed record ExportOutput(string RelativePath, string Content, string? Problem = null);

// Extra, optional rendering inputs. BasePath is needed to check which directories exist.
public sealed record RenderOptions(string? BasePath, bool NestedAgents);

public sealed record ExportTarget(
    string Name,
    string RelativePath,
    RuleStyle Style,
    string? RuleDirectory,
    string RuleExtension,
    bool InDefaultSet = true,
    bool AlwaysOnTriggerInSingleLayout = false,
    // File name used for nested per-directory files (AGENTS.md only).
    string? NestedFileName = null)
{
    public string ResolvePath(string basePath) => ResolveRelative(basePath, RelativePath);

    public static string ResolveRelative(string basePath, string relativePath)
    {
        var segments = new List<string> { basePath };
        segments.AddRange(relativePath.Split('/'));
        return Path.Combine(segments.ToArray());
    }

    public IReadOnlyList<ExportOutput> Render(ExportContext exportContext, ExportLayout layout, RenderOptions? options = null) =>
        ContextExporter.Render(this, exportContext, layout, options);

    // The main file of the single layout.
    public string Build(ExportContext exportContext) =>
        Render(exportContext, ExportLayout.Single)[0].Content;
}

public static class ExportTargets
{
    public const string GeneratedRulePrefix = "aicontext-";

    public static IReadOnlyList<ExportTarget> All { get; } =
    [
        new("agents", "AGENTS.md", RuleStyle.None, null, ".md", NestedFileName: "AGENTS.md"),
        new("copilot", ".github/copilot-instructions.md", RuleStyle.Copilot, ".github/instructions", ".instructions.md"),
        new("claude", "CLAUDE.md", RuleStyle.Claude, ".claude/rules", ".md"),
        new("cursor", ".cursor/rules/project.mdc", RuleStyle.Cursor, ".cursor/rules", ".mdc"),
        new("windsurf", ".windsurf/rules/project.md", RuleStyle.Windsurf, ".windsurf/rules", ".md"),
        // Devin also loads .windsurf/rules, so it is opt-in and excluded from the default "all" set.
        new("devin", ".devin/rules/project.md", RuleStyle.Windsurf, ".devin/rules", ".md",
            InDefaultSet: false, AlwaysOnTriggerInSingleLayout: true),
        new("aider", "CONVENTIONS.md", RuleStyle.None, null, ".md")
    ];

    public static IReadOnlyList<string> Names { get; } = All.Select(x => x.Name).ToArray();

    // Targets generated by "export --target all" when exports.targets is not configured.
    public static IReadOnlyList<string> DefaultNames { get; } = All.Where(x => x.InDefaultSet).Select(x => x.Name).ToArray();

    public static ExportTarget? Find(string name) =>
        All.FirstOrDefault(x => string.Equals(x.Name, name, StringComparison.Ordinal));
}
