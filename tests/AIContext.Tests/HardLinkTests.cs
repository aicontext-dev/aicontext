using AIContext;
using Xunit;

namespace AIContext.Tests;

// Hard links (step 05, technical audit §14 question 2). A hard link is a second name for the same file, so the path
// guard cannot tell it from a regular file: ExportPathGuard resolves symbolic links and junctions, not inode identity.
// What matters is what a write or a removal through such a name does to the file that lives outside the project.
// Writing replaces the file through a temporary file (D18), which gives the project name a new file and leaves the
// outside one alone; removing deletes only the name. Reading is not protected, and these tests state that too.
public sealed class HardLinkTests : IDisposable
{
    private const string OutsideContent = "OUTSIDE-FILE-MUST-NOT-CHANGE";

    private static readonly string GeneratedHeader = $"<!-- {ContextExporter.GeneratedMarker} --target agents -->\n";

    private readonly string _root = Path.Combine(Path.GetTempPath(), "aicontext-tests-" + Guid.NewGuid().ToString("N"));
    private readonly string _project;
    private readonly string _outside;

    public HardLinkTests()
    {
        _project = Path.Combine(_root, "project");
        _outside = Path.Combine(_root, "outside");
        Directory.CreateDirectory(_project);
        Directory.CreateDirectory(_outside);
        var init = ProjectInitializer.Initialize(_project, "demo", InitProfile.Core, ContextSchema.CanonicalUrl, "0.1.0", force: false);
        Assert.Empty(init.Conflicts);
    }

    public void Dispose() => Directory.Delete(_root, recursive: true);

    private string InProject(string relative) =>
        Path.Combine(_project, relative.Replace('/', Path.DirectorySeparatorChar));

    private string OutsideFile(string name, string content)
    {
        var path = Path.Combine(_outside, name);
        File.WriteAllText(path, content);
        return path;
    }

    private ExportPlan Plan(bool force = false) => ExportService.Plan(new ExportRequest(_project, "agents", Force: force));

    [LinkFact(LinkCapability.HardLink)]
    public void Export_GeneratedFileIsAHardLinkToAFileOutsideTheProject_LeavesTheOutsideFileUntouched()
    {
        var outside = OutsideFile("victim.md", GeneratedHeader + OutsideContent);
        TestLinks.CreateHardLink(InProject("AGENTS.md"), outside);
        var plan = Plan();
        Assert.Equal(ExportFileStatus.Updated, Assert.Single(plan.Files).Status);

        var result = ExportService.Apply(plan);

        Assert.False(result.HasErrors);
        Assert.Equal(GeneratedHeader + OutsideContent, File.ReadAllText(outside));
        Assert.DoesNotContain(OutsideContent, File.ReadAllText(InProject("AGENTS.md")));
        Assert.DoesNotContain(TestLinks.Entries(_project), name => name.EndsWith(".tmp", StringComparison.Ordinal));
    }

    [LinkFact(LinkCapability.HardLink)]
    public void Export_HandWrittenFileIsAHardLinkToAFileOutsideTheProject_IsAConflictUnlessForcedAndNeverChangesTheOutsideFile()
    {
        var outside = OutsideFile("victim.md", OutsideContent);
        TestLinks.CreateHardLink(InProject("AGENTS.md"), outside);

        var refused = Plan();
        Assert.Contains(refused.Diagnostics, d => d.IsError && d.Code == DiagnosticCodes.OverwriteConflict);
        Assert.Throws<InvalidOperationException>(() => ExportService.Apply(refused));
        Assert.Equal(OutsideContent, File.ReadAllText(outside));

        var forced = Plan(force: true);
        Assert.False(forced.HasErrors);
        Assert.False(ExportService.Apply(forced).HasErrors);
        Assert.Equal(OutsideContent, File.ReadAllText(outside));
        Assert.Contains("Auto-generated by aicontext export", File.ReadAllText(InProject("AGENTS.md")));
    }

    [LinkFact(LinkCapability.HardLink)]
    public void Export_OrphanedGeneratedFileIsAHardLinkToAFileOutsideTheProject_RemovesOnlyTheNameInTheProject()
    {
        var outside = OutsideFile("victim.md", GeneratedHeader + OutsideContent);
        Directory.CreateDirectory(InProject("docs"));
        TestLinks.CreateHardLink(InProject("docs/AGENTS.md"), outside);
        var plan = Plan();
        Assert.Contains(plan.Files, f => f.Status == ExportFileStatus.Deleted);

        var result = ExportService.Apply(plan);

        Assert.False(result.HasErrors);
        Assert.False(File.Exists(InProject("docs/AGENTS.md")));
        Assert.Equal(GeneratedHeader + OutsideContent, File.ReadAllText(outside));
    }

    [LinkFact(LinkCapability.HardLink)]
    public void Init_ForceAndASourceFileIsAHardLinkToAFileOutsideTheProject_LeavesTheOutsideFileUntouched()
    {
        File.Delete(InProject(".aicontext/README.md"));
        var outside = OutsideFile("victim.md", OutsideContent);
        TestLinks.CreateHardLink(InProject(".aicontext/README.md"), outside);

        var result = ProjectInitializer.Initialize(_project, "demo", InitProfile.Core, ContextSchema.CanonicalUrl, "0.1.0", force: true);

        Assert.False(result.HasErrors);
        Assert.Equal(OutsideContent, File.ReadAllText(outside));
        Assert.Contains("# Project: demo", File.ReadAllText(InProject(".aicontext/README.md")));
    }

    // The limit, stated as a test: a hard link in .aicontext/ is read like any other file, because it cannot be
    // told from one. Whoever creates hard links in a project decides what its context contains; a clone from git
    // cannot contain one.
    [LinkFact(LinkCapability.HardLink)]
    public void Export_SourceFileIsAHardLinkToAFileOutsideTheProject_ReadsItLikeAnyOtherFile()
    {
        File.Delete(InProject(".aicontext/README.md"));
        var outside = OutsideFile("notes.md", "# Project: demo\n\n" + OutsideContent + "\n");
        TestLinks.CreateHardLink(InProject(".aicontext/README.md"), outside);

        var result = ExportService.Apply(Plan());

        Assert.False(result.HasErrors);
        Assert.Contains(OutsideContent, File.ReadAllText(InProject("AGENTS.md")));
    }
}
