using AIContext;
using Xunit;

namespace AIContext.Tests;

public sealed class ExportWriterTests : IDisposable
{
    private readonly string _basePath = Path.Combine(Path.GetTempPath(), "aicontext-tests-" + Guid.NewGuid().ToString("N"));

    private static readonly ExportContext Context = new(
        "sample-project",
        "# Project: sample-project\n\nShort summary.\n",
        "Architecture text.",
        null,
        null,
        "Constraint text.",
        null);

    private static readonly ExportTarget Agents = ExportTargets.Find("agents")!;
    private static readonly ExportTarget Cursor = ExportTargets.Find("cursor")!;

    public ExportWriterTests()
    {
        Directory.CreateDirectory(_basePath);
    }

    public void Dispose()
    {
        Directory.Delete(_basePath, recursive: true);
    }

    [Fact]
    public void Plan_MissingFile_IsCreated_AndApplyWritesIt()
    {
        var plan = ExportWriter.Plan(Cursor, _basePath, Context, force: false);

        Assert.Equal(ExportFileStatus.Created, plan.Status);
        Assert.False(File.Exists(plan.Path));

        ExportWriter.Apply(plan);

        Assert.Equal(plan.Content, File.ReadAllText(plan.Path));
    }

    [Fact]
    public void Plan_SecondRun_IsUnchanged_AndFileIsNotRewritten()
    {
        var first = ExportWriter.Plan(Agents, _basePath, Context, force: false);
        ExportWriter.Apply(first);
        var writtenAt = File.GetLastWriteTimeUtc(first.Path);

        Thread.Sleep(50);
        var second = ExportWriter.Plan(Agents, _basePath, Context, force: false);
        ExportWriter.Apply(second);

        Assert.Equal(ExportFileStatus.Unchanged, second.Status);
        Assert.Equal(writtenAt, File.GetLastWriteTimeUtc(second.Path));
    }

    [Fact]
    public void Plan_ExistingFileWithCrlf_IsUnchanged()
    {
        var plan = ExportWriter.Plan(Agents, _basePath, Context, force: false);
        File.WriteAllText(plan.Path, plan.Content.Replace("\n", "\r\n", StringComparison.Ordinal));

        var second = ExportWriter.Plan(Agents, _basePath, Context, force: false);

        Assert.Equal(ExportFileStatus.Unchanged, second.Status);
    }

    [Fact]
    public void Plan_ChangedSource_UpdatesGeneratedFile()
    {
        ExportWriter.Apply(ExportWriter.Plan(Agents, _basePath, Context, force: false));

        var changed = Context with { Constraints = "Different constraint." };
        var plan = ExportWriter.Plan(Agents, _basePath, changed, force: false);

        Assert.Equal(ExportFileStatus.Updated, plan.Status);
    }

    [Fact]
    public void Plan_HandWrittenFile_IsConflict_AndApplyDoesNotOverwrite()
    {
        var path = Agents.ResolvePath(_basePath);
        File.WriteAllText(path, "My own instructions");

        var plan = ExportWriter.Plan(Agents, _basePath, Context, force: false);
        ExportWriter.Apply(plan);

        Assert.Equal(ExportFileStatus.Conflict, plan.Status);
        Assert.Equal("My own instructions", File.ReadAllText(path));
    }

    [Fact]
    public void Plan_HandWrittenFile_WithForce_IsUpdated()
    {
        var path = Agents.ResolvePath(_basePath);
        File.WriteAllText(path, "My own instructions");

        var plan = ExportWriter.Plan(Agents, _basePath, Context, force: true);
        ExportWriter.Apply(plan);

        Assert.Equal(ExportFileStatus.Updated, plan.Status);
        Assert.Equal(plan.Content, File.ReadAllText(path));
    }

    [Fact]
    public void Plan_LegacyGeneratedFileWithTimestamp_IsUpdatedWithoutForce()
    {
        var path = Cursor.ResolvePath(_basePath);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(
            path,
            "---\ndescription: \"x\"\nalwaysApply: true\n---\n\n" +
            "<!-- Auto-generated by aicontext export --target cursor -->\n" +
            "<!-- Source: .aicontext/ | Generated: 2026-11-01T00:00:00Z | Do not edit directly -->\n\nold");

        var plan = ExportWriter.Plan(Cursor, _basePath, Context, force: false);

        Assert.Equal(ExportFileStatus.Updated, plan.Status);
    }

    [Fact]
    public void IsGenerated_OnlyLooksAtFileHeader()
    {
        var content = string.Join('\n', Enumerable.Repeat("line", 20)) + "\n" + ContextExporter.GeneratedMarker;

        Assert.False(ExportWriter.IsGenerated(content));
        Assert.True(ExportWriter.IsGenerated($"<!-- {ContextExporter.GeneratedMarker} --target agents -->\nbody"));
    }
}
